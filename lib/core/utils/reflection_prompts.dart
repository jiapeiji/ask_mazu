//   - 每日 1 条 + 4 时辰变种(早/午/晚/深夜)
//   - 文案围绕「反思 · 记录 · 此刻」,不引导用户求签/预测
//   - 80+ 条轮换(每时辰 20+ 条),足够半年不重样
//
// 用法:
//   final prompt = ReflectionPrompts.today(DateTime.now());

class ReflectionPrompts {
