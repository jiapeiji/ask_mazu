  /// 4 个时段(基于 DateTime.hour)
  /// - 辰时 5-11  → 早安
  /// - 午时 12-17  → 午后
  /// - 戌时 18-22  → 傍晚
  /// - 亥时 23-4   → 夜深
  static String _slot(DateTime now) {
    final h = now.hour;
    if (h >= 5 && h < 12) return '早安';
    if (h >= 12 && h < 18) return '午后';
    if (h >= 18 && h < 23) return '傍晚';
    return '夜深';
  }

  /// 每日 1 条(确定性:基于 yyyymmdd 哈希到 0..19 取一条)
  static String today(DateTime now) {
    final slot = _slot(now);
    final list = _prompts[slot] ?? _prompts['早安']!;
    final seed = now.year * 10000 + now.month * 100 + now.day;
    final idx = seed % list.length;
    return list[idx];
  }

